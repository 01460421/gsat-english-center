/** '2026-10-08' → '2026 年 10 月 8 日'。 */
export function formatVersionDate(version: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(version);
  if (!m) return version;
  return `${m[1]} 年 ${Number(m[2])} 月 ${Number(m[3])} 日`;
}

